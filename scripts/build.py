#!/usr/bin/env python3
"""Check the Diversion Risk Scorer data and refresh the derived files.

Reads:
  data/derived/scores.json   the published edition the page loads
  data/raw/                  component inputs, weights, validation cases
Writes:
  data/derived/scores.csv    the scores as a flat table
and refreshes the headline block in README.md.

Score = 100 × Σ weight × component, each component on a 0 (low risk) to 1
(high risk) scale, weights normalised to sum to 1. The published scores were
computed from unrounded components; data/raw/components.csv stores them to
three decimals, so recomputed scores can differ by up to 0.1. This script
checks that, and that the published ranks, exposure and validation figures
are consistent with the scores.

The code that pulled and scaled the components from the source datasets is not
in this repository yet (see README.md).

Standard library only. Run from the repository root:  python scripts/build.py
"""
import csv
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "data", "raw")
OUT = os.path.join(ROOT, "data", "derived")
COMPONENTS = {
    "governance": "gov_risk",
    "conflict": "conflict_risk",
    "embargo": "embargo_risk",
    "neighbourhood": "neighbourhood_risk",
    "att": "att_risk",
}
TOLERANCE = 0.1


def main():
    data = json.load(open(os.path.join(OUT, "scores.json"), encoding="utf-8"))
    weights = json.load(open(os.path.join(RAW, "weights.json"), encoding="utf-8"))["weights"]
    with open(os.path.join(RAW, "components.csv"), newline="", encoding="utf-8") as f:
        inputs = {r["iso3"]: r for r in csv.DictReader(f)}
    with open(os.path.join(RAW, "validation_cases.csv"), newline="", encoding="utf-8") as f:
        cases = list(csv.DictReader(f))

    problems = []
    if weights != data["weights"]:
        problems.append("weights.json differs from the weights in scores.json")
    total = sum(weights.values())
    w = {k: v / total for k, v in weights.items()}
    countries = data["countries"]
    n = len(countries)
    if n != data["n_countries"]:
        problems.append(f"n_countries is {data['n_countries']} but {n} states are listed")

    for d in countries:
        r = inputs.get(d["iso3"])
        if r is None:
            problems.append(f"{d['iso3']} has a score but no row in components.csv")
            continue
        for col in COMPONENTS.values():
            v = float(r[col])
            if not 0 <= v <= 1:
                problems.append(f"{d['iso3']}: {col} = {v} outside 0-1")
            if abs(v - d[col]) > 1e-9:
                problems.append(f"{d['iso3']}: {col} differs between components.csv and scores.json")
        score = sum(100 * w[k] * float(r[c]) for k, c in COMPONENTS.items())
        if abs(score - d["risk_score"]) > TOLERANCE:
            problems.append(f"{d['iso3']}: recomputed score {score:.2f} vs published {d['risk_score']}")

    ranked = sorted(countries, key=lambda d: d["rank"])
    for a, b in zip(ranked, ranked[1:]):
        if a["risk_score"] < b["risk_score"]:
            problems.append(f"rank order broken between {a['iso3']} and {b['iso3']}")
    by_iso = {d["iso3"]: d for d in countries}
    published = {(v["iso3"], v["mode"]) for v in data["validation"]}
    for c in cases:
        if (c["iso3"], c["mode"]) not in published:
            problems.append(f"validation case {c['iso3']} ({c['mode']}) missing from scores.json")
        if c["iso3"] not in by_iso:
            problems.append(f"validation case {c['iso3']} is not a scored state")

    cols = ["rank", "iso3", "name", "region", "income", "risk_score", "rank_p05", "rank_p95"] + \
        list(COMPONENTS.values()) + ["att_status", "embargo_bodies", "arms_imp_tiv_m_2015on",
                                     "battle_deaths_2020on", "exposure", "exposure_rank", "embargo_note"]
    with open(os.path.join(OUT, "scores.csv"), "w", encoding="utf-8", newline="") as f:
        wr = csv.DictWriter(f, fieldnames=cols, lineterminator="\n", extrasaction="ignore")
        wr.writeheader()
        wr.writerows(ranked)

    update_readme(data, ranked)
    print(f"{n} states checked; top 5: " + ", ".join(f"{d['name']} {d['risk_score']}" for d in ranked[:5]))
    if problems:
        raise SystemExit("Checks failed:\n" + "\n".join(problems))
    print("All checks passed.")


def update_readme(data, ranked):
    path = os.path.join(ROOT, "README.md")
    if not os.path.exists(path):
        return
    leak = [v for v in data["validation"] if v["mode"] == "leakage"]
    retr = [v for v in data["validation"] if v["mode"] == "re-transfer"]
    avg = lambda l: round(sum(v["percentile"] for v in l) / len(l)) if l else 0
    block = (
        "<!-- HEADLINE:START (generated by scripts/build.py, do not edit by hand) -->\n"
        f"**Highest diversion risk at the base weights** (snapshot {data['built']}, {data['n_countries']} states): "
        + "; ".join(f"{d['rank']}. {d['name']} ({d['risk_score']})" for d in ranked[:10]) + ".\n\n"
        f"Known diversion cases sit at a mean percentile of {avg(leak)} for leakage from weak states "
        f"but {avg(retr)} for deliberate re-transfer by governments: the model catches the first far "
        f"better than the second.\n"
        "<!-- HEADLINE:END -->"
    )
    text = open(path, encoding="utf-8").read()
    new = re.sub(r"<!-- HEADLINE:START.*?<!-- HEADLINE:END -->", block, text, flags=re.S)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)


if __name__ == "__main__":
    main()
